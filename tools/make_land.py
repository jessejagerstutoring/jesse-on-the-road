"""Turns Natural Earth country shapes (public domain, world-atlas countries-50m.json) into
src/land.js, a compact grid that says which country each spot on Earth belongs to.
Only needed once.

Usage: python3 -I tools/make_land.py path/to/countries-50m.json src/land.js
Dutch country names come from tools/countries_nl.json.
"""
import json, sys
from pathlib import Path

RES, LAT_TOP, LAT_BOTTOM = 0.25, 84.0, -58.0
W, H = int(360 / RES), int((LAT_TOP - LAT_BOTTOM) / RES)

# The source abbreviates some names. On the map they should read in full.
FULL_NAMES = {
    "United States of America": "United States", "Dem. Rep. Congo": "DR Congo",
    "Central African Rep.": "Central African Republic", "Bosnia and Herz.": "Bosnia and Herzegovina",
    "Dominican Rep.": "Dominican Republic", "Eq. Guinea": "Equatorial Guinea", "S. Sudan": "South Sudan",
    "W. Sahara": "Western Sahara", "Côte d'Ivoire": "Ivory Coast", "eSwatini": "Eswatini",
    "N. Cyprus": "Northern Cyprus", "Fr. S. Antarctic Lands": "French Southern Lands",
    "Fr. Polynesia": "French Polynesia", "S. Geo. and the Is.": "South Georgia",
    "Antigua and Barb.": "Antigua and Barbuda", "St. Kitts and Nevis": "Saint Kitts and Nevis",
    "St. Vin. and Gren.": "Saint Vincent", "Macedonia": "North Macedonia", "São Tomé and Principe": "Sao Tome and Principe",
}


def full_name(name):
    name = FULL_NAMES.get(name, name)
    return name.replace(" Is.", " Islands").replace("St. ", "Saint ")


topo = json.load(open(sys.argv[1]))
sx, sy = topo["transform"]["scale"]
tx, ty = topo["transform"]["translate"]

arcs = []
for arc in topo["arcs"]:
    x = y = 0
    points = []
    for dx, dy in arc:
        x += dx
        y += dy
        points.append((x * sx + tx, y * sy + ty))
    arcs.append(points)


def ring(indices):
    points = []
    for i in indices:
        points += arcs[i] if i >= 0 else arcs[~i][::-1]
    return points


names = []
grid = [bytearray(W) for _ in range(H)]
for geometry in topo["objects"]["countries"]["geometries"]:
    kind = geometry.get("type")
    if kind == "Polygon":
        polygons = [geometry["arcs"]]
    elif kind == "MultiPolygon":
        polygons = geometry["arcs"]
    else:
        continue
    name = full_name(geometry["properties"]["name"])
    if name in names:
        country = names.index(name) + 1
    else:
        names.append(name)
        country = len(names)
    for polygon in polygons:
        crossings = {}
        for indices in polygon:
            points = ring(indices)
            for (x1, y1), (x2, y2) in zip(points, points[1:]):
                if y1 == y2:
                    continue
                r1, r2 = (LAT_TOP - y1) / RES - 0.5, (LAT_TOP - y2) / RES - 0.5
                low, high = min(r1, r2), max(r1, r2)
                for row in range(max(0, int(low) + 1 if low > 0 else 0), min(H - 1, int(high)) + 1):
                    if low <= row < high:
                        t = (row - r1) / (r2 - r1)
                        crossings.setdefault(row, []).append((x1 + t * (x2 - x1) + 180) / RES)
        for row, xs in crossings.items():
            xs.sort()
            for a, b in zip(xs[0::2], xs[1::2]):
                start, end = max(0, round(a)), min(W, round(b))
                if end > start:
                    grid[row][start:end] = bytes([country]) * (end - start)

rows = []
for line in grid:
    runs, value, count = [], line[0], 0
    for cell in line:
        if cell == value:
            count += 1
        else:
            runs.append(f"{value:x}:{count:x}")
            value, count = cell, 1
    runs.append(f"{value:x}:{count:x}")
    rows.append(".".join(runs))

data = ";".join(rows)
dutch = json.loads((Path(__file__).parent / "countries_nl.json").read_text(encoding="utf-8"))
missing = [n for n in names if n not in dutch]
if missing:
    sys.exit(f"No Dutch name for: {missing}")
nl = [dutch[n] for n in names]
with open(sys.argv[2], "w", encoding="utf-8") as out:
    out.write(
        "// Country grid made from Natural Earth (public domain). Generated by tools/make_land.py.\n"
        f'window.LAND={{w:{W},h:{H},res:{RES},top:{LAT_TOP},names:{json.dumps(names, ensure_ascii=False)},nl:{json.dumps(nl, ensure_ascii=False)},rle:"{data}"}};\n'
    )
print(f"{len(names)} countries, {W}x{H}, {len(data) / 1024:.0f} KB")
